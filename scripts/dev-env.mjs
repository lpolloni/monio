#!/usr/bin/env node
// Writes .env.local using the credentials reported by the running local
// Supabase DEV stack (`supabase status -o env`). Values are never invented:
// if the stack is not running, the script fails.
//
// Existing non-Supabase entries in .env.local (AI_*, BLOCKCHAIN_*, ...) are kept.

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const envPath = path.join(root, ".env.local");

function parseEnv(text) {
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (!m) continue;
    let value = m[2];
    if (/^".*"$/.test(value) || /^'.*'$/.test(value)) value = value.slice(1, -1);
    out[m[1]] = value;
  }
  return out;
}

let statusOutput;
try {
  statusOutput = execFileSync("npx", ["supabase", "status", "-o", "env"], {
    cwd: root,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
} catch (error) {
  console.error("Could not read `supabase status`. Is the DEV stack running? Try `npm run dev:services`.");
  console.error(String(error.stderr ?? error.message));
  process.exit(1);
}

const status = parseEnv(statusOutput);
const publishable = status.PUBLISHABLE_KEY ?? status.ANON_KEY;
const secret = status.SECRET_KEY ?? status.SERVICE_ROLE_KEY;
if (!status.API_URL || !publishable || !secret) {
  console.error("`supabase status` did not report API_URL / keys. Refusing to write placeholder values.");
  process.exit(1);
}

const existing = existsSync(envPath) ? parseEnv(readFileSync(envPath, "utf8")) : {};

const managed = {
  APP_ENV: "development",
  NEXT_PUBLIC_SUPABASE_URL: status.API_URL,
  NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: publishable,
  SUPABASE_SERVICE_ROLE_KEY: secret,
  SUPABASE_DB_URL: status.DB_URL ?? "",
};

const defaults = {
  AI_PROVIDER: "mock",
  AI_BASE_URL: "http://192.168.68.115:8000/v1",
  AI_API_KEY: "",
  AI_MODEL: "Qwen3.5-9B-MLX-4bit",
  AI_TIMEOUT_MS: "20000",
  AI_ALLOW_CLOUD_DOCUMENTS: "false",
  BLOCKCHAIN_PROVIDER: "mock",
  BLOCKCHAIN_API_URL: "",
  BLOCKCHAIN_API_KEY: "",
  EXCHANGE_RATE_PROVIDER: "mock",
  EXCHANGE_RATE_API_URL: "",
  EXCHANGE_RATE_API_KEY: "",
  IMPORT_MAX_FILE_MB: "15",
};

const merged = { ...defaults, ...existing, ...managed };
const lines = [
  "# Generated by scripts/dev-env.mjs from the local Supabase DEV stack.",
  "# Never commit this file. Re-run `npm run dev:env` after `supabase start`.",
  ...Object.entries(merged).map(([k, v]) => `${k}=${v}`),
  "",
];
writeFileSync(envPath, lines.join("\n"), { mode: 0o600 });
console.log(`Wrote ${path.relative(root, envPath)} (${Object.keys(merged).length} variables).`);
